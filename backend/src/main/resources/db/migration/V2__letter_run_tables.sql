-- Tables owned by case-service for admin letter generation. Only facts that can't be
-- calculated are stored: the generated count, the run status and per-item status are
-- derived on read from case_documents (and the queue flag).

-- One row per letter type. Generate takes SELECT ... FOR UPDATE on the row
-- for its type, which serialises generation per type. Never updated; add a row
-- in the migration that introduces a new letter type.
CREATE TABLE letter_type_lock (
  letter_type VARCHAR(40) PRIMARY KEY
);

-- One row per Generate click.
-- Identity columns use the SQL-standard GENERATED BY DEFAULT AS IDENTITY
-- (H2, PostgreSQL, Oracle 12c+, DB2). Real DB may differ: e.g. SQL Server
-- uses IDENTITY(1,1), MySQL uses AUTO_INCREMENT.
CREATE TABLE letter_run (
  run_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  letter_type           VARCHAR(40)  NOT NULL,
  claim_submitted_date  DATE         NOT NULL,  -- as entered by the admin
  visibility            VARCHAR(20)  NOT NULL,  -- STAFF_ONLY | STAFF_AND_EXTERNAL; starts STAFF_ONLY
  total_requested       INT          NOT NULL,  -- number of run items, set once at Generate
  requested_by          VARCHAR(100) NOT NULL,
  requested_at          TIMESTAMP    NOT NULL,
  completed_at          TIMESTAMP,              -- set the first time every item has a document
  released_by           VARCHAR(100),
  released_at           TIMESTAMP
);

-- One row per application in a run, recorded once at Generate. letter_type is copied
-- from the run so the external visibility check needs no join. The queue key
-- (appid_lettertype) is built in the queue insert, not stored.
CREATE TABLE letter_run_item (
  run_id       BIGINT      NOT NULL REFERENCES letter_run(run_id),
  app_id       VARCHAR(40) NOT NULL,
  letter_type  VARCHAR(40) NOT NULL,
  PRIMARY KEY (run_id, app_id)
);
-- For the external visibility check (latest run = highest run_id) and eligibility.
CREATE INDEX ix_item_app_type_run ON letter_run_item (app_id, letter_type, run_id);
